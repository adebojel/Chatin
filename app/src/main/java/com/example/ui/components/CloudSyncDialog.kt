/**
 * Displays the real availability state. Cloud backup/synchronization is not wired
 * to an authenticated storage provider, so this dialog intentionally offers no
 * action that could imply a successful backup.
 */
@Composable
fun CloudSyncDialog(
    user: UserAccount?,
    onSyncNow: () -> Unit,
    onUpdateProfile: (String, String, String) -> Unit,
    onDismiss: () -> Unit
) {
    Dialog(
        onDismissRequest = onDismiss,
        properties = DialogProperties(usePlatformDefaultWidth = false)
    ) {
        Surface(
            modifier = Modifier
                .fillMaxWidth(0.92f)
                .padding(12.dp),
            shape = RoundedCornerShape(24.dp),
            color = MaterialTheme.colorScheme.surface,
            tonalElevation = 8.dp
        ) {
            Column(
                modifier = Modifier.padding(24.dp),
                horizontalAlignment = Alignment.CenterHorizontally,
                verticalArrangement = Arrangement.Center
            ) {
                Icon(
                    imageVector = Icons.Default.CloudOff,
                    contentDescription = null,
                    tint = MaterialTheme.colorScheme.onSurfaceVariant
                )
                Spacer(modifier = Modifier.height(12.dp))
                Text(
                    text = "Sinkronisasi cloud belum tersedia",
                    fontSize = 18.sp,
                    fontWeight = FontWeight.Bold,
                    color = MaterialTheme.colorScheme.onSurface
                )
                Spacer(modifier = Modifier.height(8.dp))
                Text(
                    text = "Chatin belum terhubung ke layanan backup dan pemulihan cloud yang terverifikasi. Data tidak akan ditandai tersimpan atau tersinkron sebelum server mengonfirmasinya.",
                    fontSize = 13.sp,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )
                Spacer(modifier = Modifier.height(20.dp))
                Button(
                    onClick = onDismiss,
                    modifier = Modifier.fillMaxWidth(),
                    shape = RoundedCornerShape(12.dp),
                    colors = ButtonDefaults.buttonColors(
                        containerColor = Color(0xFF00AFAF)
                    )
                ) {
                    Text("Tutup", color = Color.White, fontWeight = FontWeight.SemiBold)
                }
            }
        }
    }
}
